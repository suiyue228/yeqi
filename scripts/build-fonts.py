"""Optional font asset maintenance; not needed to install, run or build the app.

python -m pip install fonttools brotli
python scripts/build-fonts.py --display /path/ZhuqueFangsong-Regular.ttf --hand /path/Xiaolai-Regular.ttf
See public/fonts/README.md for pinned upstream sources and licenses.
"""

import argparse
import hashlib
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "public" / "fonts"


def unicode_ranges(codes):
    groups = []
    for code in sorted(codes):
        if groups and code == groups[-1][1] + 1:
            groups[-1][1] = code
        else:
            groups.append([code, code])
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in groups)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--display", type=Path, required=True)
    parser.add_argument("--hand", type=Path, required=True)
    args = parser.parse_args()
    DEST.mkdir(exist_ok=True)
    interface = "夜栖月下树洞记忆档案馆月下小剧场写给今夜的信今夜回响"
    for path in sorted((ROOT / "src").rglob("*")):
        if path.suffix in (".tsx", ".ts") and ".test." not in path.name:
            interface += path.read_text(encoding="utf-8-sig")
    static_codes = set(map(ord, interface))
    latin = set(range(32, 256)) | set(range(0x2000, 0x2070)) | set(range(0x3000, 0x3040)) | set(range(0xFF00, 0xFFEF))
    # Common GB2312 characters first: rare characters never inflate ordinary letters.
    common = set()
    for lead in range(0xB0, 0xD8):
        for trail in range(0xA1, 0xFF):
            try:
                common.add(ord(bytes([lead, trail]).decode("gb2312")))
            except UnicodeDecodeError:
                pass
    css = ["/* Generated by scripts/build-fonts.py. Keep OFL files with the fonts. */"]
    manifest = {"generator": "fontTools 4.65.0 / brotli 1.2.1", "families": []}
    for source, family, stem, limited in [
        (args.display, "Moonlit Display", "display", True),
        (args.hand, "Moonlit Hand", "hand", False),
    ]:
        original = TTFont(source)
        cmap = original.getBestCmap()
        wanted = (static_codes | latin) & set(cmap) if limited else set(cmap)
        groups = [wanted & latin]
        remainder = wanted - groups[0]
        interface_codes = sorted(remainder & static_codes)
        groups.extend(set(interface_codes[i:i + 384]) for i in range(0, len(interface_codes), 384))
        remainder -= set(interface_codes)
        preferred = sorted(remainder & common)
        groups.extend(set(preferred[i:i + 384]) for i in range(0, len(preferred), 384))
        remainder -= set(preferred)
        rare = sorted(remainder)
        groups.extend(set(rare[i:i + 512]) for i in range(0, len(rare), 512))
        records = []
        for i, codes in enumerate(groups):
            if not codes:
                continue
            font = TTFont(source, recalcTimestamp=False)
            options = subset.Options()
            options.recalc_timestamp = False
            options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
            options.name_legacy = True
            options.name_languages = ["*"]
            selector = subset.Subsetter(options=options)
            selector.populate(unicodes=codes)
            selector.subset(font)
            # Derivatives use project aliases; upstream authors do not endorse them.
            for record in font["name"].names:
                replacement = {1: family, 2: "Regular", 3: family + " Web", 4: family, 6: family.replace(" ", ""), 16: family, 17: "Regular"}.get(record.nameID)
                if replacement:
                    record.string = replacement.encode(record.getEncoding())
            filename = f"{stem}-v1-{i:03}.woff2"
            font.flavor = "woff2"
            font.save(DEST / filename)
            verified = TTFont(DEST / filename)
            if set(verified.getBestCmap()) != codes:
                raise ValueError(f"Subset coverage mismatch: {filename}")
            records.append({"file": filename, "bytes": (DEST / filename).stat().st_size, "sha256": hashlib.sha256((DEST / filename).read_bytes()).hexdigest(), "unicodeRange": unicode_ranges(codes), "characters": len(codes)})
            css.append(f'@font-face {{ font-family: "{family}"; font-style: normal; font-weight: 400; font-display: swap; src: url("/fonts/{filename}") format("woff2"); unicode-range: {unicode_ranges(codes)}; }}')
        manifest["families"].append({"family": family, "sourceSha256": hashlib.sha256(source.read_bytes()).hexdigest(), "sourceCharacters": len(cmap), "shippedCharacters": len(wanted), "files": records})
        print(f"{family}: {len(wanted)} characters, {len(records)} files, {sum(r['bytes'] for r in records):,} bytes", flush=True)
    (ROOT / "src" / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    (DEST / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
